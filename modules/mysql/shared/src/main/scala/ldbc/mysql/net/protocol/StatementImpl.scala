private[ldbc] case class StatementImpl[F[_]](
  protocol:             Protocol[F],
  serverVariables:      Map[String, String],
  batchedArgs:          Ref[F, Vector[String]],
  connectionClosed:     Ref[F, Boolean],
  statementClosed:      Ref[F, Boolean],
  resultSetClosed:      Ref[F, Boolean],
  currentResultSet:     Ref[F, Option[ResultSet[F]]],
  updateCount:          Ref[F, Long],
  moreResults:          Ref[F, Boolean],
  autoGeneratedKeys:    Ref[F, Int],
  lastInsertId:         Ref[F, Long],
  fetchSize:            Ref[F, Int],
  useCursorFetch:       Boolean,
  useServerPrepStmts:   Boolean,
  resultSetType:        Int             = ResultSet.TYPE_FORWARD_ONLY,
  resultSetConcurrency: Int             = ResultSet.CONCUR_READ_ONLY,
  telemetryConfig:      TelemetryConfig = TelemetryConfig.default,
  databaseMetrics:      DatabaseMetrics[F]
)(using tracer: Tracer[F], ex: Exchange[F], evF: Concurrent[F])
  extends StatementImpl.ShareStatement[F]:

  override protected def F: Concurrent[F] = evF

  private val baseAttributes    = buildBaseAttributes(protocol)
  private val metricsAttributes = buildMetricsAttributes(protocol)

  private def simpleQueryRun(sql: String): F[ResultSet[F]] =
    exchange[F, ResultSet[F]](
      telemetryConfig.resolveSpanName(
        sql,
        TelemetrySpanName.STMT_EXECUTE,
        protocol.hostInfo.database,
        Some(protocol.hostInfo.host),
        Some(protocol.hostInfo.port)
      )
    ) { (span: Span[F]) =>
      val processedSql    = telemetryConfig.processQueryText(sql)
      val queryAttributes = baseAttributes ++ List(
        DbAttributes.DbQueryText(processedSql)
      )

      withDurationMetrics(
        span.addAttributes(queryAttributes*) *>
          protocol.resetSequenceId *>
          protocol.send(ComQueryPacket(sql, protocol.initialPacket.capabilityFlags, ListMap.empty)) *>
          protocol.receive(ColumnsNumberPacket.decoder(protocol.initialPacket.capabilityFlags)).flatMap {
            case _: OKPacket =>
              for
                resultSet <- F.pure(
                               ResultSetImpl
                                 .empty(
                                   protocol,
                                   serverVariables,
                                   protocol.initialPacket.serverVersion,
                                   resultSetClosed,
                                   fetchSize,
                                   useCursorFetch,
                                   useServerPrepStmts
                                 )
                             )
                _ <- currentResultSet.set(Some(resultSet))
              yield resultSet
            case error: ERRPacket =>
              val exception = error.toException(Some(sql), None)
              span.addAttributes(error.attributes*) *>
                span.recordException(exception, error.attributes*) *>
                span.setStatus(StatusCode.Error, exception.getMessage) *>
                F.raiseError(exception)
            case result: ColumnsNumberPacket =>
              for
                columnDefinitions <-
                  protocol.repeatProcess(
                    result.size,
                    ColumnDefinitionPacket.decoder(protocol.initialPacket.capabilityFlags)
                  )
                resultSetRow <-
                  protocol.readUntilEOF[ResultSetRowPacket](
                    textResultSetRowDecoder(protocol.initialPacket.capabilityFlags)
                  )
                _ <- columnDefinitions.headOption match {
                       case None         => F.unit
                       case Some(column) => span.addAttribute(DbAttributes.DbCollectionName(column.table))
                     }
                resultSet = ResultSetImpl(
                              protocol,
                              columnDefinitions,
                              resultSetRow,
                              serverVariables,
                              protocol.initialPacket.serverVersion,
                              resultSetClosed,
                              fetchSize,
                              useCursorFetch,
                              useServerPrepStmts,
                              TextColumnValueDecoder,
                              resultSetType,
                              resultSetConcurrency,
                              Some(sql)
                            )
                _ <- currentResultSet.set(Some(resultSet))
                _ <- databaseMetrics.recordReturnedRows(resultSetRow.size.toLong, metricsAttributes*)
              yield resultSet
          },
        metricsAttributes*
      )
    }

  private def buildServerPreparedStatement(sql: String): F[PreparedStatement[F]] =
    for
      result <- protocol.resetSequenceId *> protocol.send(ComStmtPreparePacket(sql)) *>
                  protocol.receive(ComStmtPrepareOkPacket.decoder(protocol.initialPacket.capabilityFlags)).flatMap {
                    case error: ERRPacket           => F.raiseError(error.toException(Some(sql), None))
                    case ok: ComStmtPrepareOkPacket => F.pure(ok)
                  }
      _ <- protocol.repeatProcess(
             result.numParams,
             ColumnDefinitionPacket.decoder(protocol.initialPacket.capabilityFlags)
           )
      _ <- protocol.repeatProcess(
             result.numColumns,
             ColumnDefinitionPacket.decoder(protocol.initialPacket.capabilityFlags)
           )
      params            <- Ref.of(SortedMap.empty[Int, Parameter])
      batchedArgs       <- Ref.of(Vector.empty[String])
      statementClosed   <- Ref.of[F, Boolean](false)
      resultSetClosed   <- Ref.of[F, Boolean](false)
      currentResultSet  <- Ref.of[F, Option[ResultSet[F]]](None)
      updateCount       <- Ref.of(-1L)
      moreResults       <- Ref.of(false)
      autoGeneratedKeys <- Ref.of(Statement.NO_GENERATED_KEYS)
      lastInsertId      <- Ref.of(0L)
    yield ServerPreparedStatement(
      protocol,
      serverVariables,
      result.statementId,
      sql,
      params,
      batchedArgs,
      connectionClosed,
      statementClosed,
      resultSetClosed,
      currentResultSet,
      updateCount,
      moreResults,
      autoGeneratedKeys,
      lastInsertId,
      fetchSize,
      useCursorFetch,
      useServerPrepStmts,
      resultSetType,
      resultSetConcurrency,
      telemetryConfig,
      databaseMetrics
    )

  private def buildClientPreparedStatement(sql: String): F[PreparedStatement[F]] =
    for
      params            <- Ref.of(SortedMap.empty[Int, Parameter])
      batchedArgs       <- Ref.of(Vector.empty[String])
      statementClosed   <- Ref.of[F, Boolean](false)
      resultSetClosed   <- Ref.of[F, Boolean](false)
      currentResultSet  <- Ref.of[F, Option[ResultSet[F]]](None)
      updateCount       <- Ref.of(-1L)
      moreResults       <- Ref.of(false)
      autoGeneratedKeys <- Ref.of(Statement.NO_GENERATED_KEYS)
      lastInsertId      <- Ref.of(0L)
    yield ClientPreparedStatement(
      protocol,
      serverVariables,
      sql,
      params,
      batchedArgs,
      connectionClosed,
      statementClosed,
      resultSetClosed,
      currentResultSet,
      updateCount,
      moreResults,
      autoGeneratedKeys,
      lastInsertId,
      fetchSize,
      useCursorFetch,
      useServerPrepStmts,
      resultSetType,
      resultSetConcurrency,
      telemetryConfig,
      databaseMetrics
    )

  private def preparedQueryRun(sql: String): F[ResultSet[F]] =
    for
      preparedStatement <- F.pure(useServerPrepStmts)
                             .ifM[PreparedStatement[F]](
                               buildServerPreparedStatement(sql),
                               buildClientPreparedStatement(sql)
                             )
      resultSet <- preparedStatement.executeQuery()
    yield resultSet

  override def executeQuery(sql: String): F[ResultSet[F]] =
    checkClosed() *> checkNullOrEmptyQuery(sql) *>
      useServerFetch().ifM(
        preparedQueryRun(sql),
        simpleQueryRun(sql)
      )

  override def executeUpdate(sql: String): F[Int] =
    executeLargeUpdate(sql).map(_.toInt)

  override def executeLargeUpdate(sql: String): F[Long] =
    checkClosed() *> checkNullOrEmptyQuery(sql) *> exchange[F, Long](
      telemetryConfig.resolveSpanName(
        sql,
        TelemetrySpanName.STMT_EXECUTE,
        protocol.hostInfo.database,
        Some(protocol.hostInfo.host),
        Some(protocol.hostInfo.port)
      )
    ) { (span: Span[F]) =>
      val processedSql    = telemetryConfig.processQueryText(sql)
      val queryAttributes = baseAttributes ++ List(
        DbAttributes.DbQueryText(processedSql)
      )

      withDurationMetrics(
        span.addAttributes(queryAttributes*) *>
          protocol.resetSequenceId *> (
            protocol.send(ComQueryPacket(sql, protocol.initialPacket.capabilityFlags, ListMap.empty)) *>
              protocol.receive(GenericResponsePackets.decoder(protocol.initialPacket.capabilityFlags)).flatMap {
                case result: OKPacket =>
                  lastInsertId.set(result.lastInsertId) *> updateCount.updateAndGet(_ => result.affectedRows)
                case error: ERRPacket =>
                  val exception = error.toException(Some(sql), None)
                  span.addAttributes(error.attributes*) *>
                    span.recordException(exception, error.attributes*) *>
                    span.setStatus(StatusCode.Error, exception.getMessage) *>
                    F.raiseError(exception)
                case eof: EOFPacket =>
                  val exception = new SQLException("Unexpected EOF packet")
                  span.addAttribute(ErrorAttributes.ErrorType(exception.getClass.getName)) *>
                    span.recordException(exception, eof.attribute) *>
                    span.setStatus(StatusCode.Error, exception.getMessage) *>
                    F.raiseError(exception)
              }
          ),
        metricsAttributes*
      )
    }

  override def close(): F[Unit] = statementClosed.set(true) *> resultSetClosed.set(true)

  override def execute(sql: String): F[Boolean] =
    checkClosed() *> checkNullOrEmptyQuery(sql) *> {
      val trimmedUpper = sql.trim.toUpperCase
      if trimmedUpper.startsWith("SELECT") ||
        trimmedUpper.startsWith("SHOW") ||
        trimmedUpper.startsWith("DESC") ||
        trimmedUpper.startsWith("EXPLAIN") ||
        trimmedUpper.startsWith("WITH") ||
        trimmedUpper.startsWith("TABLE") ||
        trimmedUpper.startsWith("OPTIMIZE") ||
        trimmedUpper.startsWith("CHECK") ||
        trimmedUpper.startsWith("REPAIR") ||
        trimmedUpper.startsWith("ANALYZE") ||
        trimmedUpper.startsWith("(")
      then
        executeQuery(sql).flatMap {
          case resultSet: (ResultSetImpl[F] @unchecked) => resultSet.hasRows()
          case _                                        => F.pure(false)
        }
      else executeUpdate(sql).map(_ => false)
    }

  override def addBatch(sql: String): F[Unit] = batchedArgs.update(_ :+ sql)

  override def clearBatch(): F[Unit] = batchedArgs.set(Vector.empty)

  override def executeLargeBatch(): F[Array[Long]] =
    checkClosed() *> protocol.resetSequenceId *>
      protocol.comSetOption(EnumMySQLSetOption.MYSQL_OPTION_MULTI_STATEMENTS_ON) *>
      exchange[F, Array[Long]](TelemetrySpanName.STMT_EXECUTE_BATCH) { (span: Span[F]) =>
        batchedArgs.get.flatMap { args =>
          val batchAttributes = baseAttributes ++
            List(DbAttributes.DbOperationName(TelemetryAttribute.SqlOperation.BATCH)) ++
            TelemetryAttribute.dbOperationBatchSize(args.length).toList

          if args.isEmpty then F.pure(Array.empty)
          else
            withDurationMetrics(
              span.addAttributes(batchAttributes*) *>
                protocol.resetSequenceId *>
                protocol.send(
                  ComQueryPacket(args.mkString(";"), protocol.initialPacket.capabilityFlags, ListMap.empty)
                ) *>
                args
                  .foldLeft(F.pure(Vector.empty[Long])) { ($acc, _) =>
                    for
                      acc    <- $acc
                      result <-
                        protocol
                          .receive(GenericResponsePackets.decoder(protocol.initialPacket.capabilityFlags))
                          .flatMap {
                            case result: OKPacket =>
                              lastInsertId.set(result.lastInsertId) *> F.pure(acc :+ result.affectedRows)
                            case error: ERRPacket =>
                              val exception = error.toException("Failed to execute batch", acc)
                              span.addAttributes(error.attributes*) *>
                                span.recordException(exception, error.attributes*) *>
                                span.setStatus(StatusCode.Error, exception.getMessage) *>
                                F.raiseError(exception)
                            case eof: EOFPacket =>
                              val exception = new SQLException("Unexpected EOF packet")
                              span.addAttribute(ErrorAttributes.ErrorType(exception.getClass.getName)) *>
                                span.recordException(exception, eof.attribute) *>
                                span.setStatus(StatusCode.Error, exception.getMessage) *>
                                F.raiseError(exception)
                          }
                    yield result
                  }
                  .map(_.toArray),
              metricsAttributes*
            )
        }
      } <* protocol.resetSequenceId <* protocol.comSetOption(
        EnumMySQLSetOption.MYSQL_OPTION_MULTI_STATEMENTS_OFF
      ) <* clearBatch()

object StatementImpl:

  private[ldbc] trait ShareStatement[F[_]] extends Statement[F]:

    /** The effect instance used by the shared statement logic. Concrete statements supply it. */
    protected def F: Concurrent[F]
    private given Concurrent[F] = F

    def protocol:          Protocol[F]
    def serverVariables:   Map[String, String]
    def statementClosed:   Ref[F, Boolean]
    def connectionClosed:  Ref[F, Boolean]
    def resultSetClosed:   Ref[F, Boolean]
    def currentResultSet:  Ref[F, Option[ResultSet[F]]]
    def updateCount:       Ref[F, Long]
    def moreResults:       Ref[F, Boolean]
    def autoGeneratedKeys: Ref[F, Int]
    def lastInsertId:      Ref[F, Long]

    def fetchSize:          Ref[F, Int]
    def useCursorFetch:     Boolean
    def useServerPrepStmts: Boolean
    def resultSetType:      Int
    def databaseMetrics:    DatabaseMetrics[F]

    override def getGeneratedKeys(): F[ResultSet[F]] =
      autoGeneratedKeys.get.flatMap {
        case Statement.RETURN_GENERATED_KEYS =>
          for
            lastInsertId <- lastInsertId.get
            record    = ResultSetRowPacket.fromStrings(Some(lastInsertId.toString))
            resultSet = ResultSetImpl(
                          protocol,
                          Vector(new ColumnDefinitionPacket:
                            override def table:      String                     = ""
                            override def name:       String                     = "GENERATED_KEYS"
                            override def columnType: ColumnDataType             = ColumnDataType.MYSQL_TYPE_LONGLONG
                            override def flags:      Seq[ColumnDefinitionFlags] = Seq.empty
                            override def charset:    String                     = "UTF-8"),
                          Vector(record),
                          serverVariables,
                          protocol.initialPacket.serverVersion,
                          resultSetClosed,
                          fetchSize,
                          useCursorFetch,
                          useServerPrepStmts,
                          TextColumnValueDecoder
                        )
            _ <- currentResultSet.set(Some(resultSet))
          yield resultSet
        case Statement.NO_GENERATED_KEYS =>
          F.raiseError(
            new SQLException(
              "Generated keys not requested. You need to specify Statement.RETURN_GENERATED_KEYS to Statement.executeUpdate(), Statement.executeLargeUpdate() or Connection.prepareStatement()."
            )
          )
      }

    override def getResultSet():        F[Option[ResultSet[F]]] = checkClosed() *> currentResultSet.get
    override def getUpdateCount():      F[Int]                  = checkClosed() *> updateCount.get.map(_.toInt)
    override def getLargeUpdateCount(): F[Long]                 = checkClosed() *> updateCount.get
    override def getMoreResults():      F[Boolean]              = checkClosed() *> moreResults.get

    override def executeUpdate(sql: String, autoGeneratedKeys: Int): F[Int] =
      this.autoGeneratedKeys.set(autoGeneratedKeys) *> executeUpdate(sql)

    override def executeLargeUpdate(sql: String, autoGeneratedKeys: Int): F[Long] =
      this.autoGeneratedKeys.set(autoGeneratedKeys) *> executeLargeUpdate(sql)

    override def execute(sql: String, autoGeneratedKeys: Int): F[Boolean] =
      this.autoGeneratedKeys.set(autoGeneratedKeys) *> execute(sql)

    override def isClosed(): F[Boolean] =
      for
        connClosed <- connectionClosed.get
        stmtClosed <- statementClosed.get
      yield connClosed || stmtClosed

    override def executeBatch(): F[Array[Int]] = executeLargeBatch().map(_.iterator.map(_.toInt).toArray)

    override def setFetchSize(rows: Int): F[Unit] = fetchSize.set(rows)

    override def getFetchSize(): F[Int] = fetchSize.get

    override def enquoteLiteral(value: String): F[String] =
      if value == null then F.pure("NULL")
      else F.pure(StringHelper.enquoteLiteral(value, ansiQuotesEnabled, backslashEscapesEnabled))

    override def enquoteIdentifier(identifier: String, alwaysQuote: Boolean): F[String] =
      if identifier == null then F.raiseError(new SQLException("Value 'null' is not a valid identifier."))
      else if StringHelper.isSimpleIdentifier(identifier) then
        val quoteChar = if ansiQuotesEnabled then '"' else '`'
        F.pure(if alwaysQuote then s"$quoteChar$identifier$quoteChar" else identifier)
      else F.pure(StringHelper.enquoteIdentifier(identifier, ansiQuotesEnabled))

    override def enquoteNCharLiteral(value: String): F[String] =
      if value == null then F.pure("NULL")
      else F.pure(StringHelper.enquoteNCharLiteral(value, backslashEscapesEnabled))

    override def isSimpleIdentifier(identifier: String): F[Boolean] =
      F.pure(StringHelper.isSimpleIdentifier(identifier))

    private def sqlMode: String = serverVariables.getOrElse("sql_mode", "")

    private def ansiQuotesEnabled: Boolean = sqlMode.contains("ANSI_QUOTES")

    private def backslashEscapesEnabled: Boolean = !sqlMode.contains("NO_BACKSLASH_ESCAPES")

    protected def checkClosed(): F[Unit] =
      isClosed().ifM(
        close() *> F.raiseError(new SQLException("No operations allowed after statement closed.")),
        F.unit
      )

    protected def checkNullOrEmptyQuery(sql: String): F[Unit] =
      if sql.isEmpty then F.raiseError(new SQLException("Can not issue empty query."))
      else if sql == null then F.raiseError(new SQLException("Can not issue NULL query."))
      else F.unit

    protected def useServerFetch(): F[Boolean] =
      fetchSize.get.map { fetchSize =>
        useCursorFetch && fetchSize > 0 && resultSetType == ResultSet.TYPE_FORWARD_ONLY
      }

    protected def buildBaseAttributes(protocol: Protocol[F]): List[Attribute[?]] =
      List[Attribute[?]](
        DbAttributes.DbSystemName(DbAttributes.DbSystemNameValue.Mysql.value),
        ServerAttributes.ServerAddress(protocol.hostInfo.host),
        ServerAttributes.ServerPort(protocol.hostInfo.port.toLong),
        MysqlTelemetryAttribute.dbMysqlVersion(protocol.initialPacket.serverVersion.toString),
        MysqlTelemetryAttribute.dbMysqlThreadId(protocol.initialPacket.threadId)
      ) ++ protocol.hostInfo.database.map(name => DbAttributes.DbNamespace(name)).toList

    /**
     * Low-cardinality attributes suitable for metrics.
     * Excludes db.mysql.thread_id (per-connection) and db.query.text (per-query)
     * to avoid high-cardinality metric series.
     */
    protected def buildMetricsAttributes(protocol: Protocol[F]): List[Attribute[?]] =
      List[Attribute[?]](
        DbAttributes.DbSystemName(DbAttributes.DbSystemNameValue.Mysql.value),
        ServerAttributes.ServerAddress(protocol.hostInfo.host),
        ServerAttributes.ServerPort(protocol.hostInfo.port.toLong)
      ) ++ protocol.hostInfo.database.map(name => DbAttributes.DbNamespace(name)).toList

    protected def withDurationMetrics[A](operation: F[A], metricsAttributes: Attribute[?]*): F[A] =
      F.monotonic.flatMap { startTime =>
        val record: F[Unit] =
          F.monotonic.flatMap(endTime =>
            databaseMetrics.recordOperationDuration(endTime - startTime, metricsAttributes*)
          )
        operation.flatTap(_ => record).handleErrorWith(error => record >> F.raiseError(error))
      }
