package ldbc.pool

import scala.concurrent.duration.*

import ldbc.sql.*

import ldbc.effect.Resource
import ldbc.fx.{ Fx, Ref }
import ldbc.fx.concurrentFx
import ldbc.fx.syntax.*
import ldbc.fx.FxSuite

final case class Failures(
  rollback:        Boolean = false,
  statementClose:  Boolean = false,
  restoreReadOnly: Boolean = false
)

final class SessionConnection(
  val base:            MockConnection,
  val readOnly:        Ref[Boolean],
  val isolation:       Ref[Int],
  val catalog:         Ref[String],
  val schema:          Ref[String],
  val setterCalls:     Ref[Map[String, Int]],
  val statementCloses: Ref[Int],
  failures:            Failures
) extends Connection[Fx]:

  export base.{
    createStatement as _,
    getCatalog as _,
    getSchema as _,
    getTransactionIsolation as _,
    isReadOnly as _,
    prepareCall as _,
    prepareStatement as _,
    rollback as _,
    setAutoCommit as _,
    setCatalog as _,
    setReadOnly as _,
    setSchema as _,
    setTransactionIsolation as _,
    *
  }

  def totalSetterCalls: Fx[Int] = setterCalls.get.map(_.values.sum)

  private def called(name: String): Fx[Unit] =
    setterCalls.update(calls => calls.updated(name, calls.getOrElse(name, 0) + 1))

  private def statement: Fx[CallableStatement[Fx]] =
    Fx.pure(new StubCallableStatement(statementCloses, failures.statementClose))

  override def createStatement(): Fx[Statement[Fx]] = statement

  override def createStatement(resultSetType: Int, resultSetConcurrency: Int): Fx[Statement[Fx]] = statement

  override def prepareStatement(sql: String): Fx[PreparedStatement[Fx]] = statement

  override def prepareStatement(sql: String, resultSetType: Int, resultSetConcurrency: Int): Fx[PreparedStatement[Fx]] =
    statement

  override def prepareStatement(sql: String, autoGeneratedKeys: Int): Fx[PreparedStatement[Fx]] = statement

  override def prepareCall(sql: String): Fx[CallableStatement[Fx]] = statement

  override def prepareCall(sql: String, resultSetType: Int, resultSetConcurrency: Int): Fx[CallableStatement[Fx]] =
    statement

  override def setAutoCommit(autoCommit: Boolean): Fx[Unit] = called("autoCommit") *> base.setAutoCommit(autoCommit)

  override def rollback(): Fx[Unit] =
    if failures.rollback then Fx.raiseError(new SQLException("rollback failed")) else base.rollback()

  override def rollback(savepoint: Savepoint): Fx[Unit] = base.rollback(savepoint)

  override def isReadOnly: Fx[Boolean] = readOnly.get

  override def setReadOnly(value: Boolean): Fx[Unit] =
    called("readOnly") *>
      (if failures.restoreReadOnly && !value then Fx.raiseError(new SQLException("setReadOnly failed"))
       else readOnly.set(value))

  override def getTransactionIsolation(): Fx[Int] = isolation.get

  override def setTransactionIsolation(level: Int): Fx[Unit] = called("isolation") *> isolation.set(level)

  override def getCatalog(): Fx[String] = catalog.get

  override def setCatalog(value: String): Fx[Unit] = called("catalog") *> catalog.set(value)

  override def getSchema(): Fx[String] = schema.get

  override def setSchema(value: String): Fx[Unit] = called("schema") *> schema.set(value)

object SessionConnection:

  def apply(failures: Failures = Failures()): Fx[SessionConnection] =
    for
      base            <- MockConnection()
      readOnly        <- Ref.of(false)
      isolation       <- Ref.of(Connection.TRANSACTION_REPEATABLE_READ)
      catalog         <- Ref.of("connector_test")
      schema          <- Ref.of("connector_test")
      setterCalls     <- Ref.of(Map.empty[String, Int])
      statementCloses <- Ref.of(0)
    yield new SessionConnection(base, readOnly, isolation, catalog, schema, setterCalls, statementCloses, failures)

class ConnectionStateResetTest extends FxSuite:

  private val singleConnection = ConnectionPoolConfig(
    minConnections    = 1,
    maxConnections    = 1,
    connectionTimeout = 5.seconds,
    adaptiveSizing    = false
  )

  private def withPool[A](failures: Failures = Failures())(
    f: (PooledDataSource[Fx], Ref[List[SessionConnection]]) => Fx[A]
  ): Fx[A] =
    Ref.of(List.empty[SessionConnection]).flatMap { created =>
      val create: Resource[Fx, Connection[Fx]] =
        Resource.make(
          SessionConnection(failures).flatTap(c => created.update(_ :+ c)).map(c => (c: Connection[Fx]))
        )(_.close())
      PooledDataSource.fromConfig(singleConnection, create).use(pool => f(pool, created))
    }

  private def eventually(check: Fx[Boolean], attempts: Int = 100): Fx[Boolean] =
    check.flatMap { ok =>
      if ok || attempts <= 1 then Fx.pure(ok) else Fx.sleep(20.millis) *> eventually(check, attempts - 1)
    }

  private def assertEvicted(created: Ref[List[SessionConnection]]): Fx[Unit] =
    for
      conns  <- created.get
      closed <- eventually(conns.head.base.closeCount.get.map(_ == 1))
    yield
      assertEquals(conns.size, 2, "the connection that failed to reset was reused")
      assert(closed, "the connection that failed to reset was never closed")

  test("readOnly changed by a borrower is restored before the next borrower gets the connection") {
    withPool() { (pool, _) =>
      for
        _        <- pool.use(_.setReadOnly(true))
        readOnly <- pool.use(_.isReadOnly)
      yield assertEquals(readOnly, false)
    }
  }

  test("transaction isolation changed by a borrower is restored before the next borrower gets the connection") {
    withPool() { (pool, _) =>
      for
        _         <- pool.use(_.setTransactionIsolation(Connection.TRANSACTION_SERIALIZABLE))
        isolation <- pool.use(_.getTransactionIsolation())
      yield assertEquals(isolation, Connection.TRANSACTION_REPEATABLE_READ)
    }
  }

  test("schema changed by a borrower is restored before the next borrower gets the connection") {
    withPool() { (pool, _) =>
      for
        _      <- pool.use(_.setSchema("world"))
        schema <- pool.use(_.getSchema())
      yield assertEquals(schema, "connector_test")
    }
  }

  test("catalog changed by a borrower is restored before the next borrower gets the connection") {
    withPool() { (pool, _) =>
      for
        _       <- pool.use(_.setCatalog("world"))
        catalog <- pool.use(_.getCatalog())
      yield assertEquals(catalog, "connector_test")
    }
  }

  test("a property changed several times by one borrower is restored to the value it had when borrowed") {
    withPool() { (pool, _) =>
      for
        _ <- pool.use { conn =>
               conn.setTransactionIsolation(Connection.TRANSACTION_SERIALIZABLE) *>
                 conn.setTransactionIsolation(Connection.TRANSACTION_READ_COMMITTED) *>
                 conn.setReadOnly(true) *>
                 conn.setReadOnly(false) *>
                 conn.setReadOnly(true) *>
                 conn.setSchema("world") *>
                 conn.setSchema("sys")
             }
        state <- pool.use(conn =>
                   for
                     isolation <- conn.getTransactionIsolation()
                     readOnly  <- conn.isReadOnly
                     schema    <- conn.getSchema()
                   yield (isolation, readOnly, schema)
                 )
      yield assertEquals(state, (Connection.TRANSACTION_REPEATABLE_READ, false, "connector_test"))
    }
  }

  test("statements left open through every factory method are closed when the connection is returned") {
    withPool() { (pool, created) =>
      for
        _ <- pool.use { conn =>
               conn.createStatement() *>
                 conn.createStatement(ResultSet.TYPE_FORWARD_ONLY, ResultSet.CONCUR_READ_ONLY) *>
                 conn.prepareStatement("SELECT 1") *>
                 conn.prepareStatement("SELECT 1", ResultSet.TYPE_FORWARD_ONLY, ResultSet.CONCUR_READ_ONLY) *>
                 conn.prepareStatement("SELECT 1", Statement.RETURN_GENERATED_KEYS) *>
                 conn.prepareCall("CALL proc()") *>
                 conn.prepareCall("CALL proc()", ResultSet.TYPE_FORWARD_ONLY, ResultSet.CONCUR_READ_ONLY)
             }
        conns  <- created.get
        closed <- conns.head.statementCloses.get
      yield assertEquals(closed, 7)
    }
  }

  test("an auto-commit connection is not rolled back when it is returned") {
    withPool() { (pool, created) =>
      for
        _         <- pool.use(_.isValid(1))
        conns     <- created.get
        rollbacks <- conns.head.base.rollbackCount.get
      yield assertEquals(rollbacks, 0)
    }
  }

  test("an open transaction is rolled back when the connection is returned") {
    withPool() { (pool, created) =>
      for
        _          <- pool.use(_.setAutoCommit(false))
        conns      <- created.get
        rollbacks  <- conns.head.base.rollbackCount.get
        autoCommit <- pool.use(_.getAutoCommit())
      yield
        assertEquals(rollbacks, 1)
        assertEquals(autoCommit, true)
    }
  }

  test("properties the borrower did not change are not reset") {
    withPool() { (pool, created) =>
      for
        _     <- pool.use(_.isValid(1))
        conns <- created.get
        calls <- conns.head.totalSetterCalls
      yield assertEquals(calls, 0)
    }
  }

  test("only the property the borrower changed is reset") {
    withPool() { (pool, created) =>
      for
        _     <- pool.use(_.setReadOnly(true))
        conns <- created.get
        calls <- conns.head.setterCalls.get
      yield assertEquals(calls, Map("readOnly" -> 2))
    }
  }

  test("a connection whose rollback fails on return is closed and not handed to the next borrower") {
    withPool(Failures(rollback = true)) { (pool, created) =>
      for
        first <- pool.use(conn => conn.setAutoCommit(false) *> conn.isValid(1))
        _     <- pool.use(_.isValid(1))
        _     <- assertEvicted(created)
      yield assert(first)
    }
  }

  test("every open statement is closed even when closing one fails, and the connection is then discarded") {
    withPool(Failures(statementClose = true)) { (pool, created) =>
      for
        _      <- pool.use(conn => conn.createStatement() *> conn.prepareStatement("SELECT 1"))
        conns  <- created.get
        closed <- conns.head.statementCloses.get
        _      <- pool.use(_.isValid(1))
        _      <- assertEvicted(created)
      yield assertEquals(closed, 2)
    }
  }

  test("a connection whose state cannot be restored is closed and not handed to the next borrower") {
    withPool(Failures(restoreReadOnly = true)) { (pool, created) =>
      for
        _ <- pool.use(_.setReadOnly(true))
        _ <- pool.use(_.isValid(1))
        _ <- assertEvicted(created)
      yield ()
    }
  }
